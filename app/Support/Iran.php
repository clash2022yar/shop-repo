    /** @return string[] */
    public static function provinces(): array
    {
        return array_keys(self::map());
    }

    /** @return string[] */
    public static function cities(string $province): array
    {
        return self::map()[$province] ?? [];
    }

    public static function randomCity(string $province): string
    {
        $cities = self::cities($province);

        return $cities ? $cities[array_rand($cities)] : $province;
    }
